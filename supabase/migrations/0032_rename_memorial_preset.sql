-- ============================================================================
-- Marine Wallet / 0032_rename_memorial_preset
-- ----------------------------------------------------------------------------
-- カスタム登録の定型「メモリアル」を「名場面」に改める。
--
-- 0031 で記録達成を3つに分けた結果、「メモリアル」の役割は
-- 「記録ではないが記念したい出来事」だけになった。ところが野球で
-- メモリアルというと節目の試合を指すことがあり、記録達成の3つと紛らわしい。
-- 「記録」と「名場面」なら、どちらに入れるか迷わない。
--
-- あわせて、既にある「メモリアル」の積立を実態に合わせて付け替える。
-- 中身は「#51山口 シーズンHR30本記念」で、これはシーズン記録そのもの。
-- 金額は同じ1,000円なので、付け替えても合計は変わらない。
--
-- 積立はラベルを写して持つので、定型を消しても過去の記録は消えない。
--
-- 冪等性: 何度実行しても安全。
-- ============================================================================

update public.saving_custom_presets set label = '名場面' where label = 'メモリアル';

-- シーズン記録が無いうちに走らせても壊れないよう、あるときだけ付け替える
update public.saving_entries
set title = 'シーズン記録'
where kind = 'custom'
  and title = 'メモリアル'
  and other_note like '%シーズン%'
  and exists (select 1 from public.saving_custom_presets where label = 'シーズン記録');

-- 残った「メモリアル」は名場面として扱う
update public.saving_entries
set title = '名場面'
where kind = 'custom' and title = 'メモリアル';
