-- ============================================================================
-- Marine Wallet / 0071_drink_items
-- ----------------------------------------------------------------------------
-- 分量を「名前・数・単位」に分ける。
--
-- 0069 では1行の自由文で持たせた。だが自由に書けると、「水300」「水 300ml」
-- 「お水300cc」が並んで、同じものか見分けが付かない。単位を選ばせれば
-- 書き方が1つに決まる。
--
-- 持ち方は jsonb の配列にする。
--   [{"name": "水", "amount": 300, "unit": "ml"}, ...]
--
-- 別表にしないのは、材料だけを検索したり集計したりしないから。レシピを
-- 開いたときに一緒に読むものなので、同じ行に入れておくほうが読みやすい。
--
-- 画面からは ingredients を読み書きしなくなるので、列も外す。
-- 本番にはまだ1件も入っていないので、移し替えるものは無い。
--
-- 冪等性: 何度実行しても安全。
-- ============================================================================

alter table public.drink_recipes
  add column if not exists items jsonb not null default '[]'::jsonb;

comment on column public.drink_recipes.items is
  '分量。[{name, amount, unit}] の配列。unit は ml/L/g/個/枚/杯/小さじ/大さじ/適量（0071）';

alter table public.drink_recipes drop column if exists ingredients;
