-- カスタム登録の定型を、記録の重みで3つに分ける。
--
-- 0030 で「記録達成」を1つ足したが、記録によって重みがまるで違う。
-- 名球会の入会条件（通算2000安打 / 200勝 / 250セーブ）は球史に残る水準で、
-- 通算1000試合出場（過去545人）と同じ金額にすると釣り合わない。
--
--   名球会記録 … 通算2000安打 / 200勝 / 250セーブ
--   生涯記録   … それ以外の通算記録（1000試合出場、200本塁打、800試合登板 など）
--   シーズン記録 … その年だけの記録（シーズン30本塁打 など）
--
-- シーズン記録は npb.jp の「達成が予想される記録」に載らない（通算記録だけの
-- ページのため）。自動では入らないので、手入力のための定型として置く。
--
-- 金額はどれも貯金ルールの画面から変えられる。ここに置く値は出発点で、
-- 既にある定型（完全試合5,000円 / ノーヒットノーラン3,000円）と釣り合う
-- ところに置いてある。
--
-- 冪等性: 何度実行しても安全。
-- ============================================================================

-- 0030 で入れた「記録達成」は、3つに分けたので役目を終える。
-- 積立の行はラベルを写して持つので、消しても過去の記録は変わらない
delete from public.saving_custom_presets where label = '記録達成';

insert into public.saving_custom_presets (label, amount, sort_order) values
  ('名球会記録', 5000, 50),
  ('生涯記録', 1000, 60),
  ('シーズン記録', 1000, 70)
on conflict (label) do nothing;
