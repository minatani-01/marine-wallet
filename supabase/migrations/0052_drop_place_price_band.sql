-- ============================================================================
-- Marine Wallet / 0052_drop_place_price_band
-- ----------------------------------------------------------------------------
-- 価格帯（price_band）をやめる。
--
-- 3段階で持たせたが、使わないことになった。低・中・高のどれを押すかを
-- 決めるのに迷う割に、絞り込んだ先で見たいものが変わらなかった。
-- 列を残しておくと、次に画面を作る人が「これは何か」を調べることになる。
--
-- 一度だけ入っていた 0050 を取り消すためのもの。0050 を実行していない
-- 環境でも、実行してある環境でも、そのまま流せる。
--
-- 冪等性: 何度実行しても安全。
-- ============================================================================

alter table public.places
  drop constraint if exists places_price_band_check;

drop index if exists public.places_price_band_idx;

alter table public.places
  drop column if exists price_band;
