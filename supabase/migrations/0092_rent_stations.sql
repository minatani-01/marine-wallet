-- ============================================================================
-- Marine Wallet / 0092_rent_stations
-- ----------------------------------------------------------------------------
-- 賃貸さがしで選べる駅の一覧。
--
-- 駅は外に聞かず、ここに登録したものから選ぶ。駅データの API や OSM に頼ると、
-- 届かない日に駅が入れられなくなる（本番から OSM に届かなかった）。路線名も
-- ここで持つので、「JR山手線 御徒町駅」のように出し分けられる。
--
-- 座標は空で入れる。初めて選ばれたときに Google で1回だけ引いて書き戻す
-- （resolved_at）。手で入れた座標は数百 m ずれることがあり、徒歩◯分の円が
-- ずれる。1回引いたあとは外に出ない。
--
-- 同じ駅名でも路線が違えば別の行。中野坂上には丸ノ内線と都営大江戸線が
-- 通っていて、どちらで通うかは住む人の都合で変わる。
--
-- まずは東京23区を中心に 604 駅。足りなければ行を足す。
--
-- 冪等性: 何度実行しても安全。
-- ============================================================================

create table if not exists public.rent_stations (
  id uuid primary key default gen_random_uuid(),
  /** 路線名。人が呼ぶ名前（JR山手線・東京メトロ銀座線・都営大江戸線） */
  line text not null,
  /** 駅名。「駅」まで含める */
  name text not null,
  /** 座標。初めて選ばれたときに引いて書き戻す。空なら未解決 */
  lat double precision,
  lng double precision,
  /** 座標を引いた日時。空なら未解決 */
  resolved_at timestamptz,
  /** 並び順。路線の並び × 100 ＋ 路線の中の順 */
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  unique (line, name)
);

comment on table public.rent_stations is
  '賃貸さがしで選べる駅（0092）。路線ごとに1行。座標は初回に引いて書き戻す';

create index if not exists rent_stations_sort_idx on public.rent_stations (sort_order);

alter table public.rent_stations enable row level security;

-- 読むのはログインしていれば誰でも（共通の参照データ）。
-- 座標の書き戻しは master だけ。行を足す・消すのは SQL からだけ行う。
drop policy if exists rent_stations_select_all on public.rent_stations;
create policy rent_stations_select_all on public.rent_stations
  for select to authenticated using (true);

drop policy if exists rent_stations_update_master on public.rent_stations;
create policy rent_stations_update_master on public.rent_stations
  for update to authenticated
  using (exists (select 1 from public.profiles p where p.id = (select auth.uid()) and p.is_master))
  with check (exists (select 1 from public.profiles p where p.id = (select auth.uid()) and p.is_master));

