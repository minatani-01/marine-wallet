-- ============================================================================
-- Marine Wallet / 0034_preset_amounts
-- ----------------------------------------------------------------------------
-- 定型の金額を見直す。
--
--   名球会記録 5,000 -> 3,000
--   名場面     1,000 ->   100
--
-- 生涯記録・シーズン記録は 1,000 のまま。
--
-- 名場面は「記録ではないが残しておきたい出来事」で、実際に入っている4件も
-- 100円で積んである。定型の側だけ 1,000 のままだと、選ぶたびに直すことになる。
--
-- すでに積み立てた分の金額は変えない。過去の月の合計が動くと、
-- 確定済みの額と食い違うため。ここで決めるのはこれから積む分の出発点。
--
-- 冪等性: 何度実行しても安全。
-- ============================================================================

update public.saving_custom_presets set amount = 3000 where label = '名球会記録';
update public.saving_custom_presets set amount = 1000 where label = '生涯記録';
update public.saving_custom_presets set amount = 1000 where label = 'シーズン記録';
update public.saving_custom_presets set amount = 100 where label = '名場面';
