-- ============================================================================
-- Marine Wallet / 0052_record_target_date
-- ----------------------------------------------------------------------------
-- 「何月何日分」を、決済した日とは別に持てるようにする。
--
-- いまの date は、払った日である。ところが観戦チケットもサウナの予約も、
-- 払う日と行く日が違う。9月25日に払った10月6日のサウナ、9月5日に払った
-- 10月4日の試合、といった具合になる。
--
-- date が1つしかないので、行く日は内容に書き足すしかなかった。
-- 「10/6 KUDOCHI sauna 銀座店」「千葉ロッテ10月4日チケ代」のように、
-- 店名やチケットの名前の前に日付が付く。人が読むぶんには通じるが、
-- 並べ替えにも絞り込みにも使えず、書き方も人によって揺れる。
--
-- 列に分ける。空でもよい。コンビニで何かを買ったときのように、払った日が
-- そのまま対象の日である記録のほうが多い。埋めさせると手間が増えるだけで、
-- 同じ日を二度入れることになる。
--
-- 並べ替えは date のまま変えない。「最近払ったもの」を上に出すほうが、
-- 精算の話をするときの順番に合う。
--
-- 冪等性: 何度実行しても安全。
-- ============================================================================

alter table public.records
  add column if not exists target_date date;

comment on column public.records.target_date is
  '何月何日分か。観戦日・予約日など、払った日（date）と違うときだけ入れる';

-- 対象の日で引きたくなったとき用。入っている行だけを対象にする
create index if not exists records_target_date_idx
  on public.records (target_date)
  where target_date is not null;
