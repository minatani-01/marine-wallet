-- ============================================================================
-- Marine Wallet / 0060_game_contributors
-- ----------------------------------------------------------------------------
-- 試合ごとに「誰が何をしたか」を置く場所を作る。
--
--   本塁打    打った選手と号数
--   勝利投手
--   セーブ投手
--   ホールド投手
--
-- npb.jp のボックススコアは責任投手（勝・敗・S）しか書かない。ホールドは
-- 毎日まるごと保存している個人投手成績を前日と比べて出す。組み立ては
-- lib/npb/contributors.ts にまとめてある。
--
-- 金額には関わらない。積立の計算は games の本塁打数や勝敗から出しており、
-- ここは画面に名前を出すためだけに持つ。空でも計算は変わらない。
--
-- 冪等性: 何度実行しても安全。
-- ============================================================================

alter table public.games
  add column if not exists contributors jsonb not null default '{}'::jsonb;

comment on column public.games.contributors is
  '誰が何をしたか。{home_runs:[{number,name,no}], win, save, holds:[]}。'
  '金額には関わらない。画面に名前を出すためだけに持つ（0060）';
