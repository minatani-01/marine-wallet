-- ============================================================================
-- Marine Wallet / 0056_team_record_tier
-- ----------------------------------------------------------------------------
-- 球団の記録を「球団記録」として分け、金額を別に決められるようにする。
--
-- npb.jp の通算記録には球団のページ（milestones_team.html）があり、取り込みは
-- 前から動いていた。ただ置き場所が「生涯記録」しかなく、選手の通算記録と
-- 同じ棚に入っていた。
--
-- 人の記録と球団の記録は重みが違う。「マリーンズ 5500敗」と「益田 通算250
-- セーブ」を同じ金額にするかどうかは、金額の問題ではなく棚の問題である。
-- 棚を分けて、金額は画面から決めてもらう。
--
-- 出発点は1000円にする。いまの生涯記録と同じなので、金額を触るまでは
-- これまでと同じ動きになる。
--
-- 既に入っている球団の記録（マリーンズ 5500敗記念）も新しい棚へ移す。
-- 金額は同じなので、積み立てた額は1円も変わらない。積立側のラベルも
-- 揃えておかないと、履歴に「生涯記録」と出たままになる。
--
-- 冪等性: 何度実行しても安全。
-- ============================================================================

-- ----------------------------------------------------------------------------
-- 1. 定型
-- ----------------------------------------------------------------------------
-- auto = true なので、カスタム登録のプルダウンには出ない。
-- 貯金ルールの「記録達成の金額」に金額だけが並ぶ（0033）
insert into public.saving_custom_presets (label, amount, sort_order, auto)
values ('球団記録', 1000, 140, true)
on conflict (label) do update set auto = true;

-- ----------------------------------------------------------------------------
-- 2. 既にある球団の記録を移す
-- ----------------------------------------------------------------------------
update public.npb_milestones
set tier = '球団記録'
where kind = 'team' and tier <> '球団記録';

-- 積立側のラベルも揃える。金額（amount）には触らない。
-- 突き合わせは other_note（例: 「マリーンズ 5500敗記念」）で行う
update public.saving_entries e
set
  title = '球団記録',
  breakdown = jsonb_build_array(
    jsonb_build_object('key', 'custom', 'label', '球団記録', 'amount', e.amount)
  )
from public.npb_milestones m
where m.kind = 'team'
  and e.kind = 'custom'
  and e.title = '生涯記録'
  and e.other_note like m.title || '%';
