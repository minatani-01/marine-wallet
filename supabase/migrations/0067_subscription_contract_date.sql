-- ============================================================================
-- Marine Wallet / 0067_subscription_contract_date
-- ----------------------------------------------------------------------------
-- anchor_on は「契約日」である、と言い直す。
--
-- 0066 では「支払日」として入れてもらっていた。だが入れる人からすると、
-- 分かっているのは契約した日のほうで、次に落ちる日はそこから数えた結果でしかない。
-- 3か月ごとのものを「次はいつか」から書かせると、数え間違いがそのまま入る。
--
-- 持ち方は変えない（日付1つ）。入れてもらうものの呼び名と、画面の見せ方だけ
-- 変える。支払日は契約日と周期から出して、入力欄の下に出す。
--
-- started_on は 0065 で作ったが一度も書いていない。契約日が anchor_on に
-- 入る以上、同じ意味の列が2つ並ぶことになるので外す。
--
-- 冪等性: 何度実行しても安全。
-- ============================================================================

comment on column public.subscriptions.anchor_on is
  '契約日。ここを起点に周期ぶんずつ進めて支払日を出す（0067）';

alter table public.subscriptions drop column if exists started_on;
