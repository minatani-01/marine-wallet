-- ============================================================================
-- Marine Wallet / 0070_drink_amounts_only
-- ----------------------------------------------------------------------------
-- 特製ドリンクは名前と分量だけにする。
--
-- 0069 では「いつ飲むか」と「作り方・メモ」も持たせた。だが書くことが
-- 増えるほど残らなくなる。作り方が要るほど込み入ったものは、そもそも
-- 思い出せる。見たいのは分量である。
--
-- 画面からは読み書きしなくなったので、列も外す。
--
-- 冪等性: 何度実行しても安全。
-- ============================================================================

alter table public.drink_recipes drop column if exists timing;
alter table public.drink_recipes drop column if exists note;

comment on column public.drink_recipes.ingredients is
  '分量。1行1つ。材料と量をまとめて書く（例: プロテイン 30g）（0070）';
